<h1 id="sandbox-cesnet-invenio">Sandbox CESNET Invenio</h1>
<p>Sandbox CESNET Invenio je instance platformy CESNET Invenio.</p>
<p>Samotný <a href="https://nrp-cz.github.io/docs/" target="_blank">CESNET Invenio</a> je rozšířením <a href="https://inveniordm.docs.cern.ch/" target="_blank">InvenioRDM</a>, platformy pro správu výzkumných dat založené na Invenio Frameworku a Zenodu. CESNET Invenio je jedním z hlavních repozitářových systémů <a href="https://www.eosc.cz/projekty/narodni-repozitarova-platforma-pro-vyzkumna-data-nrp/nrp">Národní repozitární platformy (NRP)</a>. Více informací o podmínkách pro vytvoření nové instance systému CESNET Invenio v NRP naleznete v části <a href="https://www.eosc.cz/sluzby/ukladani/repozitare-v-nrp">Repozitáře v NRP</a>.</p>

<h2>Cíl sandboxu</h2>
<ul>
<li>Umožnit komukoli si vyzkoušet standardní funkce CESNET Invenio v bezpečném prostředí</li>
<li>Vyzkoušení procesu ukládání dat a popisu metadat v Invenio implementaci Czech Core Metadata Model (CCMM)</li>
<li>Vyzkoušení API a testování ukládacích skriptů a datových kanálů</li>
<li>Seznámení se s datovými repozitáři v kurzech a workshopech</li>
</ul>

<h2>Základní pravidla užívání</h2>
<ul>
<li>Prostřednictvím e-INFRA se může zaregistrovat kdokoli a jeho registrace je automaticky schválena s možností ukládání dat (v repozitáři Catch-all musí uživatelé požádat o povolení k ukládání dat a čekat na schválení).</li>
<li>Komunitu může vytvořit jakýkoli uživatel.</li>
<li>Repozitář má dvě demo komunity, kde si uživatelé mohou vyzkoušet standardní pracovní postupy ukládání.</li>
<li>Repozitář přiřazuje pouze testovací DOI, které nelze vyřešit.</li>
<li>Data jsou pravidelně mazána.</li>
</ul>

<h2>Technická poznámka</h2>
<p>Kód CESNET Invenio sandboxu vychází z kódu Catch-all datového repozitáře a sdílí stejnou architekturu a funkce. Hlavní rozdíly spočívají v automatickém povolení k ukládání dat a vytváření komunit. Jinak je uživatelská dokumentace k Catch-alldatovému repozitáři (viz níže) platná i zde.</p>

