<h1 id="sandbox-cesnet-invenio">Sandbox CESNET Invenio</h1>
<p>Sandbox CESNET Invenio je fork Ctach-all datového repozitáře spravovaný NRP metodiky Invenio.</p>
<p>Samotný <a href="https://nrp-cz.github.io/docs/">CESNET Invenio</a> je rozšířením <a href="https://inveniordm.docs.cern.ch/">InvenioRDM</a>, platformy pro správu výzkumných dat založené na Invenio Frameworku a Zenodu. CESNET Invenio je jedním z hlavních repozitářových systémů <a href="https://www.eosc.cz/projekty/narodni-repozitarova-platforma-pro-vyzkumna-data-nrp/nrp">Národní repozitární platformy (NRP)</a>. Více informací o podmínkách pro vytvoření nové instance systému CESNET Invenio v NRP naleznete v části <a href="https://www.eosc.cz/sluzby/ukladani/repozitare-v-nrp">Repozitáře v NRP</a>.</p>
<h2 id="c-l-sandboxu">Cíl sandboxu</h2>
<ul>
<li>Umožnit komukoli si vyzkoušet standardní funkce CESNET Invenio v bezpečném prostředí</li>
<li>Vyzkoušení procesu ukládání dat a popisu metadat v Invenio implementaci Czech Core Metadata Model (CCMM)</li>
<li>Vyzkoušení API a testování ukládacích skriptů a datových kanálů</li>
<li>Seznámení se s datovými repozitáři v kurzech a workshopech</li>
</ul>
<h2 id="jak-se-li-od-catch-all-datov-ho-repozit-e-">Jak se liší od Catch-all datového repozitáře?</h2>
<ul>
<li>Prostřednictvím e-INFRA se může zaregistrovat kdokoli a jeho registrace je automaticky schválena s možností ukládání dat (v repozitáři Catch-all musí uživatelé požádat o povolení k ukládání dat a čekat na schválení).</li>
<li>Komunitu může vytvořit jakýkoli uživatel (v repozitáři Catch-all může nové komunity vytvářet pouze správce repozitáře).</li>
<li>Repozitář má dvě demo komunity, kde si uživatelé mohou vyzkoušet standardní pracovní postupy ukládání.</li>
<li>Repozitář přiřazuje pouze testovací DOI, které nelze vyřešit.</li>
<li>Data jsou pravidelně mazána.</li>
</ul>
